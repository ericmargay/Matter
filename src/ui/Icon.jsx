import { PATHS } from './iconos'

export default function Icon({ name, size = 18, className = '' }) {
  const d = PATHS[name] ?? PATHS.hub
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.5"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
    >
      <path d={d} />
    </svg>
  )
}
